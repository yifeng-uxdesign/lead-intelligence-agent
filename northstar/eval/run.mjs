// Replays northstar/eval/scenarios.json against the widget engine and prints Markdown.
// usage: ./run.sh > baseline-YYYY-MM-DD.md   (read-only: imports engine.js, scenarios.js, config.js unmodified)
import { readFileSync } from "node:fs";
import { pathToFileURL, fileURLToPath } from "node:url";
import { join, dirname } from "node:path";
const widgetDir = process.argv[2];
const here = dirname(fileURLToPath(import.meta.url));
const { createConversation } = await import(pathToFileURL(join(widgetDir, "engine.js")));
const { WIDGET_CONFIG } = await import(pathToFileURL(join(widgetDir, "config.js")));
const { NODES } = await import(pathToFileURL(join(widgetDir, "scenarios.js")));
const spec = JSON.parse(readFileSync(join(here, "scenarios.json"), "utf8"));

async function play(messages) {
  const conv = createConversation({ config: WIDGET_CONFIG, onTypingDelay: () => 0 });
  const rows = [];
  for (const u of messages) {
    const before = conv.getState();
    const n = before.messages.length;
    const prev = NODES[before.nodeId];
    await conv.send(u);
    const after = conv.getState();
    const reply = after.messages.slice(n + 1).filter((m) => m.role === "assistant").map((m) => m.text).join("\n\n");
    const fb = !!(prev?.fallback?.text && reply.startsWith(prev.fallback.text));
    rows.push({ u, node: after.nodeId, reply, fb });
  }
  return rows;
}
const q = (t) => t.split("\n").map((l) => `> ${l}`).join("\n");
const out = [];
out.push(`# Baseline replay (${spec.version})`, "", "Generated by `northstar/eval/run.mjs` against the current engine. Deterministic: the same code gives the same output.", "`FALLBACK` marks a reply that is the previous node's own fallback text.", "");
out.push("## Round 1: scenarios exactly as written", "");
for (const s of spec.scenarios) {
  out.push(`### ${s.id}. ${s.name}`, `*${s.dimension}. ${s.persona}*`, "");
  const rows = await play(s.messages);
  rows.forEach((r, i) => {
    out.push(`**${i + 1}. Visitor:** ${r.u}`, "", `*node \`${r.node}\`${r.fb ? ", FALLBACK" : ""}*`, "", q(r.reply), "");
  });
  const same = rows.map((r, i) => (i && r.reply === rows[i - 1].reply ? i + 1 : null)).filter(Boolean);
  out.push(`*Fallbacks: ${rows.filter((r) => r.fb).length}. Identical to previous reply at turn(s): ${same.length ? same.join(", ") : "none"}.*`, "");
}
out.push("## Round 2: one interruption after each scenario", "");
out.push("| Interruption | " + spec.scenarios.map((s) => s.id).join(" | ") + " |", "|---|" + spec.scenarios.map(() => "---").join("|") + "|");
for (const it of spec.interruptions) {
  const cells = [];
  for (const s of spec.scenarios) {
    const r = (await play([...s.messages, it.text])).at(-1);
    cells.push(`\`${r.node}\`${r.fb ? " FB" : ""}`);
  }
  out.push(`| ${it.text} *(${it.tests})* | ${cells.join(" | ")} |`);
}
out.push("", "`FB` = the previous node's own fallback text was shown, whatever was said.");
console.log(out.join("\n"));
