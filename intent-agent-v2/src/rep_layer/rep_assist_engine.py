"""Rep-facing collaboration layer: internal sales use only.

Copy is concise, direct, and operational—optimized for fast scanning and action,
not customer-facing language.

**Value constitution:** ``src/core/soul.md`` governs behavioral constraints for
the whole agent system; rep-facing tone and priorities must not contradict it
(e.g. pressure tactics leaking into customer paths).

SLA and recommended actions are sourced from ``domain.trigger_catalog`` to avoid
drift with HandoffManager SLA minutes.

**Frustration escalation policy (soul.md — conflict hierarchy priority 2):**
A prospect expressing frustration or anger must always trigger an immediate rep
alert. The agent must never attempt to re-engage or de-escalate autonomously
first. Doing so would optimize for workflow over the prospect's interest, which
violates soul.md priority 2: "do not harm the prospect's interest."
See ``_FRUSTRATION_IMMEDIATE_ESCALATION_ACTION`` and the guard in
``create_alert_brief`` for the enforcement point.

TODO for maintainers: verify that ``REP_ACTION_BY_BRIEF_KEY["frustration"]``
in ``domain/trigger_catalog.py`` does NOT recommend re-engagement or autonomous
de-escalation before rep contact. If it does, update it to match
``_FRUSTRATION_IMMEDIATE_ESCALATION_ACTION`` below — the catalog must not
contradict the soul-level constraint enforced here.

**Summary honesty policy (soul.md — value 7 "memory is a responsibility" +
rep-facing guardrails):**
``conversation_summary`` flows from ``LeadContext`` into every rep-facing
output — alert briefs, CRM snapshots, Slack payloads. If it was generated by
an LLM upstream, it may silently soften a hard no ("prospect needs more time")
or inflate buying signals ("showing strong interest") in ways that mislead the
rep into acting on a false picture of the conversation.

soul.md value 7: "data is context, not ammunition — the summary passed to the
rep must reflect the conversation honestly; no softening of hard nos, no
inflation of buying signals."
soul.md rep-facing guardrails: "report conversation state accurately — no
optimistic spin."

``_validate_summary_honesty()`` is the enforcement point. It runs on every
summary before it reaches a rep surface. It does not mutate or block the
summary — it logs a warning so the rep is aware that the summary may warrant
scrutiny. Mutating LLM output at this layer would create its own distortion;
flagging preserves the original while surfacing the risk.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from typing import Dict, List, Tuple

from src.core.lead_context import LeadContext
from src.domain.trigger_catalog import (
    DEFAULT_REP_ACTION,
    REP_ACTION_BY_BRIEF_KEY,
    format_sla_display,
    sla_minutes_for_trigger,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Frustration escalation constants
# soul.md — conflict hierarchy priority 2: "do not harm the prospect's interest"
#
# Frustration is a trust-critical signal. The agent must surface it to the rep
# immediately — never attempt autonomous recovery first. The SLA override below
# ensures frustration always routes at the highest urgency tier regardless of
# what the trigger catalog returns. The action override ensures the rep brief
# instructs immediate human contact, not a retry loop.
# ---------------------------------------------------------------------------

# Highest-urgency SLA value: overrides catalog default for frustration triggers.
# Update this constant if the SLA tier system in trigger_catalog.py changes.
_FRUSTRATION_URGENCY_OVERRIDE: str = "immediate"

# Canonical rep action for frustration: must always be direct human contact.
# This overrides REP_ACTION_BY_BRIEF_KEY["frustration"] if that value
# recommends autonomous re-engagement. See module docstring TODO above.
_FRUSTRATION_IMMEDIATE_ESCALATION_ACTION: str = (
    "Contact prospect directly now — do not re-engage via agent. "
    "Acknowledge frustration personally before resuming any sales discussion."
)

# Trigger key that activates the frustration escalation guard.
_FRUSTRATION_TRIGGER: str = "frustration"

# ---------------------------------------------------------------------------
# Summary honesty validator
# soul.md — value 7 "memory is a responsibility" + rep-facing guardrails
#
# These patterns detect language that LLMs commonly use to soften negative
# signals or inflate positive ones. Each entry is a (pattern, description)
# pair. The pattern is matched case-insensitively against the summary text.
# The description is included in the warning log so the rep (or a reviewer)
# understands what kind of distortion was detected.
#
# Extend this list as new softening patterns are observed in production.
# Do not remove entries without confirming the pattern is no longer generated
# by the upstream summary model.
# ---------------------------------------------------------------------------

_SOFTENING_PATTERNS: List[Tuple[re.Pattern[str], str]] = [
    # Hard-no softeners — reframe refusal as hesitation or timing
    (re.compile(r"needs?\s+more\s+time", re.IGNORECASE),
     "softens a potential hard no into a timing issue"),
    (re.compile(r"still\s+considering", re.IGNORECASE),
     "softens a potential hard no into ongoing evaluation"),
    (re.compile(r"not\s+ready\s+yet", re.IGNORECASE),
     "softens a potential hard no into a future opportunity"),
    (re.compile(r"wants?\s+to\s+think\s+(it\s+)?over", re.IGNORECASE),
     "softens a potential hard no into a pause"),
    (re.compile(r"open\s+to\s+revisiting", re.IGNORECASE),
     "softens a potential hard no into future openness"),

    # Buying-signal inflators — amplify weak or neutral signals
    (re.compile(r"show(ing|s)?\s+strong\s+interest", re.IGNORECASE),
     "may inflate a neutral or weak signal into strong buying intent"),
    (re.compile(r"very\s+interested", re.IGNORECASE),
     "may overstate prospect enthusiasm"),
    (re.compile(r"highly\s+engaged", re.IGNORECASE),
     "may overstate prospect engagement level"),
    (re.compile(r"excited\s+about", re.IGNORECASE),
     "may attribute enthusiasm not evidenced in the conversation"),
    (re.compile(r"ready\s+to\s+move\s+forward", re.IGNORECASE),
     "may overstate readiness when commitment has not been confirmed"),
]

# Sentiments that increase the risk that a softening pattern is misleading.
# When the recorded sentiment is negative and a softening pattern fires,
# the mismatch is more likely to be distortion than accurate nuance.
_NEGATIVE_SENTIMENTS: frozenset = frozenset(
    {"negative", "frustrated", "angry", "skeptical", "dissatisfied"}
)


def _validate_summary_honesty(summary: str, sentiment: str = "") -> str:
    """Check ``summary`` for known softening or inflation patterns and warn if found.

    **soul.md — value 7 "memory is a responsibility" + rep-facing guardrails:**
    The summary passed to the rep must reflect the conversation accurately.
    This function does not mutate or block the summary — it logs a structured
    warning so the rep or a downstream reviewer knows the summary may warrant
    scrutiny. Returning the original unchanged preserves the full context while
    surfacing the risk.

    Args:
        summary: The raw ``conversation_summary`` string from ``LeadContext``.
        sentiment: The recorded sentiment label from ``LeadContext``. Used to
            assess whether a detected pattern is likely to be distorting —
            a softening phrase against a negative sentiment is a stronger signal
            of potential spin than the same phrase against a neutral sentiment.

    Returns:
        The original ``summary`` string, unchanged. The side effect is the
        warning log, not a mutation of the value.
    """
    if not summary or not summary.strip():
        return summary

    detected: List[str] = []
    sentiment_is_negative = sentiment.strip().lower() in _NEGATIVE_SENTIMENTS

    for pattern, description in _SOFTENING_PATTERNS:
        if pattern.search(summary):
            detected.append(description)

    if detected:
        sentiment_note = (
            f" Recorded sentiment is '{sentiment}' — mismatch increases distortion risk."
            if sentiment_is_negative
            else f" Recorded sentiment is '{sentiment}'."
        )
        logger.warning(
            "[soul.md honesty validator] conversation_summary may contain spin. "
            "Patterns detected: %s.%s "
            "Summary passed to rep unchanged — verify against raw conversation transcript. "
            "See soul.md value 7 and rep-facing guardrails.",
            "; ".join(detected),
            sentiment_note,
        )

    return summary


def _normalize_rep_trigger(trigger: str) -> str:
    """Map free-text or label to canonical rep-brief key."""
    t = str(trigger).strip().lower()
    t = re.sub(r"[\s\-]+", "_", t)
    synonyms = {
        "human": "human_request",
        "request_human": "human_request",
        "rep_request": "human_request",
        "buy": "buying_intent",
        "buying": "buying_intent",
        "price": "pricing",
        "quote": "pricing",
        "frustrated": "frustration",
        "angry": "frustration",
        "pricing_discussion": "pricing",
        "strong_buying_signal": "buying_intent",
    }
    return synonyms.get(t, t)


def _is_frustration_trigger(canon: str) -> bool:
    """Return True if the canonical trigger requires the frustration escalation guard."""
    return canon == _FRUSTRATION_TRIGGER


def _extract_summary(context: LeadContext) -> str:
    """Return the validated conversation summary from context.

    Runs ``_validate_summary_honesty`` before returning so every consumer
    of this helper gets the honesty check without duplicating the call.
    Both ``create_alert_brief`` and ``summarize_customer_state`` use this
    helper — soul.md value 7 is enforced once, consistently, for all
    rep-facing summary surfaces.
    """
    raw = (context.conversation_summary or "").strip() or "(no summary captured)"
    return _validate_summary_honesty(raw, sentiment=context.sentiment)


@dataclass(frozen=True)
class AlertBrief:
    """Structured alert for rep queueing—minimizes context switching."""

    lead_id: str
    trigger: str
    lead_score: int
    sentiment: str
    recommended_action: str
    summary: str
    urgency_sla: str

    def as_dict(self) -> Dict[str, object]:
        """Serialize for APIs, Slack, or CRM task payloads."""
        return {
            "lead_id": self.lead_id,
            "trigger": self.trigger,
            "lead_score": self.lead_score,
            "sentiment": self.sentiment,
            "recommended_action": self.recommended_action,
            "summary": self.summary,
            "urgency_sla": self.urgency_sla,
        }


class RepAssistEngine:
    """Surfaces high-signal alerts and actions so reps spend time on revenue, not parsing."""

    def create_alert_brief(self, context: LeadContext, trigger: str) -> AlertBrief:
        """Build a single scannable alert row from shared lead context and trigger label.

        **Frustration guard (soul.md — conflict hierarchy priority 2):**
        If the canonical trigger is ``frustration``, this method overrides both
        the catalog-sourced ``urgency_sla`` and ``recommended_action`` with
        soul-level constants that enforce immediate rep escalation. The catalog
        values are intentionally bypassed — they must never silently reintroduce
        autonomous re-engagement for this trigger.

        **Summary honesty (soul.md — value 7):**
        ``conversation_summary`` is passed through ``_extract_summary()`` which
        runs ``_validate_summary_honesty()`` before the value reaches the brief.
        The summary is not mutated — any detected patterns are logged as warnings.
        """
        canon = _normalize_rep_trigger(trigger)

        # Validate summary honesty before it reaches any rep surface.
        # soul.md value 7 "memory is a responsibility" — no spin in rep briefs.
        summary = _extract_summary(context)

        # --- Frustration escalation guard -----------------------------------
        # soul.md conflict hierarchy priority 2: "do not harm the prospect's
        # interest." Frustration signals a trust-critical moment. The agent
        # must not attempt to resolve this autonomously. Both the urgency SLA
        # and the recommended action are overridden unconditionally here so
        # that no catalog configuration can silently weaken this constraint.
        if _is_frustration_trigger(canon):
            return AlertBrief(
                lead_id=context.lead_id,
                trigger=canon,
                lead_score=context.lead_score,
                sentiment=context.sentiment,
                recommended_action=_FRUSTRATION_IMMEDIATE_ESCALATION_ACTION,
                summary=summary,
                urgency_sla=_FRUSTRATION_URGENCY_OVERRIDE,
            )
        # --- Standard path --------------------------------------------------

        recommended = self.recommend_action(trigger)
        minutes = sla_minutes_for_trigger(canon)
        sla_display = format_sla_display(minutes)

        return AlertBrief(
            lead_id=context.lead_id,
            trigger=canon,
            lead_score=context.lead_score,
            sentiment=context.sentiment,
            recommended_action=recommended,
            summary=summary,
            urgency_sla=sla_display,
        )

    def recommend_action(self, trigger: str) -> str:
        """Return the default operational play for this trigger type.

        Note: ``frustration`` triggers bypass this method entirely inside
        ``create_alert_brief`` — the soul-level override takes precedence.
        This method should not be called directly for frustration triggers.
        """
        canon = _normalize_rep_trigger(trigger)
        return REP_ACTION_BY_BRIEF_KEY.get(canon, DEFAULT_REP_ACTION)

    def summarize_customer_state(self, context: LeadContext) -> str:
        """One-line operational snapshot for CRM sidebar or mobile push body.

        **Summary honesty (soul.md — value 7):**
        Summary text is validated through ``_extract_summary()`` before being
        appended to the snapshot string. Detected softening patterns are logged
        as warnings. The value is not mutated.
        """
        rep = context.assigned_rep or "unassigned"
        online = "online" if context.rep_online else "offline"

        # Validate summary honesty before surfacing to CRM or push body.
        # soul.md value 7 "memory is a responsibility" — no spin in rep snapshots.
        summ = _extract_summary(context)

        tail = f" | {summ[:120]}..." if len(summ) > 120 else (f" | {summ}" if summ else "")

        return (
            f"{context.lead_id} | score {context.lead_score} | {context.sentiment} | "
            f"state={context.customer_state} | mode={context.collaboration_mode} | "
            f"rep={rep} ({online}){tail}"
        )