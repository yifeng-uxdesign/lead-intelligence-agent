def placeholders_in_yaml(doc: Dict[str, Any]) -> Dict[str, Set[str]]:
    out: Dict[str, Set[str]] = dict(signals=set(), triggers=set(), fields=set(), invariants=set())
    for c in doc["cases"]:
        for t in c["turns"]:
            out["signals"].update(t.get("extraction", {}).get("signals_present", []))
            d = t.get("decision", {})
            out["fields"].update(d.keys())
            if d.get("trigger"):
                out["triggers"].add(d["trigger"])
            out["invariants"].update(t.get("invariants", []))
    out["invariants"].update(doc.get("global_invariants", []))
    return out
