"""YAML placeholder -> real code name mapping (config A).

Single source of truth for the runner AND for MAPPING.md (generated by
gen_mapping_md.py). The YAML files are never renamed or edited; this module is
where placeholders are interpreted.

Labels used in notes: "from code" (cited file:line), "inferred".
A mapping `status` is one of:
  exact   - same concept exists in code
  partial - a nearby code concept exists; it is weaker/different (see note)
  none    - DOES NOT EXIST in code
`pred(trace)` -> bool says whether the placeholder is present in an adapter trace.
`inject` is a dict of LeadSignals field overrides used by structured mode;
None means the placeholder cannot be expressed as a LeadSignals value.
"""

