"""Build REPORT_A.md from results/config_a_results.json (run the suite first).

Classification of each failed check (see REPORT_A.md "How failures are classified"):
  invariant violation | missing feature | bad expectation (inferred) |
  extraction miss (fails free_text only) | decision bug (fails both) |
  decision bug (structured only)
"""
import collections
import json
import os
import sys

import checks
import mapping

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "results", "config_a_results.json")))
SC = {c["id"]: c for c in checks.SCEN["cases"]}
checks_only = [r for r in R if not r["layer"].startswith("_")]
traces = {(r["case"], r["input_mode"]): r["actual"] for r in R if r["layer"] == "_trace"}
static = next(r["actual"] for r in R if r["layer"] == "_static")

by_key = collections.defaultdict(dict)  # (case,turn,check) -> {mode: record}
for r in checks_only:
    by_key[(r["case"], r["turn"], r["check"])][r["input_mode"]] = r


def turn_has_noninjectable(case, turn):
    return any(r["check"] == "injection" and r["case"] == case and r["turn"] == turn for r in checks_only)


def classify(r):
    c, n = _classify(r)
    extra = mapping.TURN_NOTES.get((r["case"], r["turn"]))
    return c, (n + " | " + extra if extra and r["layer"] != "invariants" else n)


def _classify(r):
    case, turn, check, mode = r["case"], r["turn"], r["check"], r["input_mode"]
    if r["layer"] == "invariants":
        return "invariant violation", ""
    if r["layer"] == "perturbation":
        if check == "signal_recorded_as":
            return "missing feature", "no 'unknown' signal state"
        if check in ("handoff", "trigger") and "signals.human_request=False" in (r["note"] or ""):
            return "extraction miss (fails free_text only)", "inferred: no structured counterpart was run; signals.human_request was False, so the extractor did not recognise the phrase"
        if check == "no_repeat_of_previous_reply":
            return "decision bug (perturbation)", "from code: verbatim holding follow-up repeat = known gap POL-26 (conformance/known_gaps.json)"
        if check == "no_canned_fallback_loop":
            return "decision bug (perturbation)", "from code: orchestrator.guard_against_repetition (170-189) swapped in a loop breaker because the scripted reply repeated"
        return "decision bug (perturbation)", ""
    if check.startswith("signal:"):
        name = check.split(":", 1)[1]
        m = mapping.SIGNALS.get(name)
        if m is None or m["status"] == "none":
            return "missing feature", "signal has no code counterpart"
        return "extraction miss (fails free_text only)", f"mapping={m['status']}"
    bad = mapping.BAD_EXPECTATION.get((case, turn, check))
    if bad and bad.startswith("inferred:"):
        return "bad expectation (inferred)", bad
    if check in mapping.MISSING_FIELDS:
        return "missing feature", f"field `{check}` does not exist in code"
    want = SC[case]["turns"][turn - 1].get("decision", {}).get(check)
    if check == "trigger" and want and mapping.TRIGGERS.get(want, {}).get("status") == "none":
        return "missing feature", f"trigger `{want}` does not exist in code"
    other = by_key[(case, turn, check)]
    ft, st = other.get("free_text"), other.get("structured")
    if mode == "free_text":
        if st is not None and st["status"] == "pass":
            return "extraction miss (fails free_text only)", "passes with injected signals; cause is raw-text matching (extractor or signal_adapters lexical rules)"
        if turn_has_noninjectable(case, turn):
            return "missing feature", "fails both; turn has expected signals that cannot be injected, so structured mode is not a clean isolate"
        return "decision bug (fails both)", ""
    # structured
    if turn_has_noninjectable(case, turn):
        return "missing feature", "input not expressible as LeadSignals (non-injectable placeholders), neutral signals used"
    if ft is not None and ft["status"] == "pass":
        return "decision bug (structured only)", "passes in free_text; check the injection mapping"
    return "decision bug (fails both)", ""


fails = []
for r in checks_only:
    if r["status"] == "fail":
        c, note = classify(r)
        fails.append(dict(r, cls=c, cnote=note))

L = []
w = L.append
w("# REPORT_A — config A (rules + templates, no LLM) against scenarios_v0.yaml\n")
w("Generated by `evals/report_a.py` from `evals/results/config_a_results.json`. Reproduce: `cd evals && PYTHONDONTWRITEBYTECODE=1 python3 -m pytest test_config_a.py; python3 report_a.py`.\n")
w("Labels: **from code** (cited), **from the YAML**, **inferred**. No source outside `evals/` was modified; no YAML expectation was edited.\n")
w("{{ANALYSIS}}")

# --- counts
w("\n## 1. Pass/fail counts\n")
w("Check status meanings: `pass`, `fail`, `unasserted` (YAML `open` or judge-only), `not_evaluable` (code has no field to check). A case/mode **test passes only if it has zero failed checks**.\n")
w("### 1a. Per case, per mode (checks)\n")
w("| case | mode | tests | checks pass | checks fail | unasserted | not_evaluable |\n|---|---|---|---|---|---|---|")
for cid in SC:
    for mode in ("free_text", "structured"):
        rs = [r for r in checks_only if r["case"] == cid and r["input_mode"] == mode]
        cnt = collections.Counter(r["status"] for r in rs)
        w(f"| {cid} | {mode} | {'FAIL' if cnt['fail'] else 'PASS'} | {cnt['pass']} | {cnt['fail']} | {cnt['unasserted']} | {cnt['not_evaluable']} |")
rs = [r for r in checks_only if r["input_mode"] == "perturbation"]
cnt = collections.Counter(r["status"] for r in rs)
pt = collections.defaultdict(lambda: collections.Counter())
for r in rs:
    pt[r["case"]][r["status"]] += 1
nfail_pt = sum(1 for c in pt.values() if c["fail"])
w(f"| 36 derived perturbation cases | free_text | {len(pt)-nfail_pt} pass / {nfail_pt} fail | {cnt['pass']} | {cnt['fail']} | {cnt['unasserted']} | {cnt['not_evaluable']} |\n")

w("### 1b. Per layer, per mode (checks)\n")
w("Layer of a check: extraction = `signal:*`; mode = `mode`/`mode_any_of`; gates = `handoff`/`trigger`; state = `qualification`/`fit_assessment`/`context_preserved`/`next_question_targets_any_of`; invariants; perturbation.\n")
w("| layer | mode | pass | fail | unasserted | not_evaluable |\n|---|---|---|---|---|---|")
for layer in ("extraction", "mode", "gates", "state", "invariants", "perturbation"):
    for mode in ("free_text", "structured", "perturbation"):
        rs = [r for r in checks_only if r["layer"] == layer and r["input_mode"] == mode]
        if not rs:
            continue
        cnt = collections.Counter(r["status"] for r in rs)
        w(f"| {layer} | {mode} | {cnt['pass']} | {cnt['fail']} | {cnt['unasserted']} | {cnt['not_evaluable']} |")

w("\n### 1c. Failures by classification\n")
w("| classification | free_text | structured | perturbation |\n|---|---|---|---|")
cc = collections.defaultdict(collections.Counter)
for f in fails:
    cc[f["cls"]][f["input_mode"]] += 1
for k, v in sorted(cc.items()):
    w(f"| {k} | {v['free_text']} | {v['structured']} | {v['perturbation']} |")

# --- handoff definition sensitivity
w("\n### 1d. Sensitivity: definition of `handoff`\n")
w("The YAML says `handoff: true|false` without defining it (inferred ambiguity). Main runs use **broad** = a trigger fired this turn OR an intervention is open (rep notified/queued; code name `handoff_triggered`, orchestrator.py:450). **Strict** = a person must take over (intervention-class trigger or open intervention; trigger_catalog.py:46-57). Same checks re-scored:\n")
w("| case | mode | handoff checks | pass (broad) | pass (strict) | checks that flip |\n|---|---|---|---|---|---|")
for cid in SC:
    for mode in ("free_text", "structured"):
        hs = [r for r in checks_only if r["case"] == cid and r["input_mode"] == mode and r["check"] == "handoff" and r["status"] != "unasserted"]
        if not hs:
            continue
        b = sum(1 for r in hs if r["status"] == "pass")
        st = sum(1 for r in hs if r["alt_takeover"] == r["expected"])
        flips = [f"t{r['turn']}" for r in hs if (r["status"] == "pass") != (r["alt_takeover"] == r["expected"])]
        w(f"| {cid} | {mode} | {len(hs)} | {b} | {st} | {', '.join(flips) or '-'} |")

# --- all failures
w("\n## 2. Every failure\n")
w("Columns: case, turn, mode, layer/check, expected (from the YAML), actual (from code run), classification. Classification of `bad expectation` is **inferred**; the owner decides.\n")
for cid in list(SC) + sorted({f['case'] for f in fails if '+' in f['case']}):
    fs = [f for f in fails if f["case"] == cid]
    if not fs:
        continue
    w(f"\n### {cid}\n")
    w("| turn | mode | layer / check | expected | actual | classification | note |\n|---|---|---|---|---|---|---|")
    for f in fs:
        e = str(f["expected"]).replace("|", "\\|")[:90]
        a = str(f["actual"]).replace("|", "\\|")[:90]
        n = (f["cnote"] or f["note"] or "").replace("|", "\\|")[:200]
        w(f"| {f['turn']} | {f['input_mode']} | {f['layer']} / {f['check']} | {e} | {a} | {f['cls']} | {n} |")

# --- unasserted
w("\n## 3. Unasserted fields (`open` in the YAML, or judge-only)\n")
w("| case | turn | field | reason |\n|---|---|---|---|")
seen = set()
for r in checks_only:
    if r["status"] == "unasserted":
        k = (r["case"], r["turn"], r["check"])
        if k in seen:
            continue
        seen.add(k)
        w(f"| {r['case']} | {r['turn']} | {r['check']} | {r['note']} |")

w("\n### 3b. Not evaluable (code has no field; neither pass nor fail)\n")
w("| check | count | example note |\n|---|---|---|")
ne = collections.defaultdict(list)
for r in checks_only:
    if r["status"] == "not_evaluable":
        ne[r["check"]].append(r)
for k, v in sorted(ne.items()):
    w(f"| {k} | {len(v)} | {v[0]['note'] or v[0]['actual']} |")

# --- static
w("\n## 4. Static template audit\n")
w(f"Scanned **{static['templates']}** distinct customer-visible strings (behavior_engine states x topics x fit x rep-name, holding copy incl. AI-disclosure variants, loop breakers) against **{static['patterns']}** `text_pattern`s from invariants_v0.yaml. Invariants without a pattern: {static['no_pattern']}.\n")
if static["hits"]:
    w("| invariant | template | match |\n|---|---|---|")
    for h in static["hits"]:
        w(f"| {h['invariant']} | {h['template']} | `{h['match']}` |")
else:
    w("**0 hits.** A self-test (`test_static_audit_selftest`) confirms the scanner flags a known-bad string, so 0 is not a silent failure. Caveat from the YAML: regex matches affirmative claims only and misses paraphrases; the bank is small and fixed, so the audit is stronger than the runtime regex for config A.\n")

# --- invariants per id
w("\n## 5. Invariant results (runtime)\n")
w("| invariant | pass | fail | not_evaluable |\n|---|---|---|---|")
inv = collections.defaultdict(collections.Counter)
for r in checks_only:
    if r["layer"] == "invariants":
        inv[r["check"]][r["status"]] += 1
for k, v in sorted(inv.items()):
    w(f"| {k} | {v['pass']} | {v['fail']} | {v['not_evaluable']} |")

# --- flaky
w("\n## 6. Flaky / nondeterministic\n")
det = next((r for r in R if r["layer"] == "_det"), None)
w("- `test_determinism_and_replay`: each scenario run twice and via stateless `adapter.run_turn(history, message)`: " + (det["actual"] if det else "NOT RUN / FAILED") + ".")
w("- Config A has no randomness in code (from code: no LLM/RNG in the pipeline). Not observed: none.\n")

# --- replies excerpt
w("\n## 7. What the agent actually said (free_text run)\n")
for cid in SC:
    w(f"\n### {cid}\n")
    w("| turn | mode | trust | trigger / open | response source | reply (first 150 chars) |\n|---|---|---|---|---|---|")
    for t in traces[(cid, "free_text")]:
        rp = (t["reply"] or "").replace("|", "\\|").replace("\n", " ")[:150]
        w(f"| {t['turn']} | {t['mode']} | {t['trust']} | {t['trigger']} | {t['src']} | {rp} |")

out = "\n".join(L)
analysis = open(os.path.join(HERE, "report_a_analysis.md")).read() if os.path.exists(os.path.join(HERE, "report_a_analysis.md")) else ""
out = out.replace("{{ANALYSIS}}", analysis)
open(os.path.join(HERE, "REPORT_A.md"), "w").write(out + "\n")
print("wrote REPORT_A.md;", len(fails), "failures")
